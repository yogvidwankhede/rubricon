def doc_files() -> list[Path]:
    files = sorted(p for p in DOC_ROOT.rglob("*.md")) if DOC_ROOT.is_dir() else []
    for extra in EXTRA_DOCS:
        p = REPO_ROOT / extra
        if p.is_file():
            files.append(p)
    return files


def audit() -> int:
    if not PORTFOLIO.is_file():
        print(f"FATAL: {PORTFOLIO} not found. Run `make run` first.")
        return 1

    raw = PORTFOLIO.read_bytes()
    digest = hashlib.md5(raw).hexdigest()
    portfolio = json.loads(raw)

    base: set[float] = set()
    collect_results_values(portfolio, base)

    secondary: list[tuple[str, str]] = []
    for path in SECONDARY_RESULTS:
        rel = path.relative_to(REPO_ROOT).as_posix()
        if not path.is_file():
            secondary.append((rel, "ABSENT -- its figures cannot be checked"))
            continue
        payload = path.read_bytes()
        collect_results_values(json.loads(payload), base)
        secondary.append((rel, hashlib.md5(payload).hexdigest()))

    buckets = build_buckets(derived_forms(base))
    allow_values, allow_patterns = split_allowlist()

    print("=" * 78)
    print("RUBRICON NUMBER AUDIT")
    print("=" * 78)
    print(f"results/portfolio.json md5 : {digest}")
    for rel, note in secondary:
        print(f"{rel + ' md5':<27}: {note}")
    print(f"distinct results values    : {len(base)}")
    print(f"allowlist entries          : {len(ALLOWLIST)} "
          f"({len(allow_values)} values, {len(allow_patterns)} line patterns)")
    print()

    files = doc_files()
    total_checked = 0
    total_sourced = 0
    total_allowed = 0
    unsourced_by_file: dict[Path, list[tuple[int, str, str]]] = {}

    for path in files:
        lines = strip_code_blocks(path.read_text(encoding="utf-8").splitlines())
        problems: list[tuple[int, str, str]] = []
        checked = sourced = allowed = 0

        for lineno, line in enumerate(lines, start=1):
            for raw, value, decimals in literals_in_line(line):
                checked += 1
                if is_sourced(value, decimals, buckets):
                    sourced += 1
                    continue
                # Value-based exclusions run only on numbers that already
                # failed to trace, so they can never mask a live figure.
                if decimals == 0 and YEAR_MIN <= value <= YEAR_MAX:
                    allowed += 1
                    continue
                if allowlist_hit(value, line, allow_values, allow_patterns):
                    allowed += 1
                    continue
                problems.append((lineno, raw, line.strip()))

        total_checked += checked
        total_sourced += sourced
        total_allowed += allowed
        rel = path.relative_to(REPO_ROOT)
        status = "OK" if not problems else f"{len(problems)} UNSOURCED"
        print(f"{str(rel):<48} {checked:>4} literals  {sourced:>4} sourced  "
              f"{allowed:>3} allowed  {status}")
        if problems:
            unsourced_by_file[rel] = problems

    print()
    if unsourced_by_file:
        print("-" * 78)
        print("UNSOURCED NUMBERS")
        print("-" * 78)
        for rel, problems in unsourced_by_file.items():
            print()
            print(f"{rel}")
            for lineno, raw, context in problems:
                if len(context) > 150:
                    context = context[:147] + "..."
                print(f"  line {lineno:>4}  {raw:>12}   {context}")
        print()

    print("=" * 78)
    print(f"SUMMARY  {total_checked} literals checked | {total_sourced} traced to "
          f"portfolio.json | {total_allowed} allowlisted | "
          f"{sum(len(v) for v in unsourced_by_file.values())} unsourced")
    print("=" * 78)

    if unsourced_by_file:
        print("FAIL: the documentation quotes numbers that do not appear in the "
              "current results.")
        print("      Either correct the document, or -- if the number genuinely "
              "has another")
        print("      source -- add a justified ALLOWLIST entry naming that source.")
        return 1

    print("PASS: every number in the documentation traces to "
          f"portfolio.json (md5 {digest}) or to a justified allowlist entry.")
    return 0


if __name__ == "__main__":
    sys.exit(audit())

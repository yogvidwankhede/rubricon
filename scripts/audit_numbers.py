#!/usr/bin/env python3
"""Audit every quantitative claim in the docs against the generated results.

WHY THIS EXISTS
---------------
This repository makes a promise: the numbers in its prose come from
`results/portfolio.json`, and anyone can check. That promise decays silently.
The moment somebody re-runs the pipeline -- a seed changes, a threshold moves,
a probe is rewritten -- every figure typed into a spec, an ADR or a protocol
becomes a claim about a run that no longer exists. Nothing errors. The
documents still read as confident and internally consistent; they are simply
describing a different experiment.

Prose and results drift apart by default, and the only defence that survives
contact with a deadline is a mechanical one. So: extract every numeric literal
from the documentation, extract every number that appears anywhere in the
generated results, and require that the first set is contained in the second.
Numbers that legitimately do not come from results -- rubric weights, published
reference values, pre-registered thresholds, dates -- must be named explicitly
in ALLOWLIST below, each with a written justification. An allowlist entry
without a justification is just a silenced alarm, so the justification is
mandatory rather than decorative.

The script is itself a portfolio artifact. A repository that claims its numbers
are traceable should be able to prove it on demand:

    PYTHONPATH=src python3 scripts/audit_numbers.py     # or: make audit

Exit code 0 means every number in the docs traces to the current results or to
a justified allowlist entry. Exit code 1 means at least one does not.

HOW IT WORKS
------------
1.  Load `results/portfolio.json` and `results/sensitivity.json`, and collect
    every number appearing anywhere in them -- including numbers embedded
    inside strings, because the pipeline writes a great deal of its evidence as
    prose ("alpha=0.584 supports ..."). `sensitivity.json` is a first-class
    source: it is generated by the same pipeline, from the same corpus, by
    `make sensitivity`, and the documents quote it for every statement about
    how conditional a verdict is. Allowlisting those figures instead would have
    exempted the newest and least-reviewed numbers in the repository from the
    only check on them.
2.  Expand that into a value set with the derived forms a document would
    plausibly quote: the raw value, its percentage form (x*100), and its
    halved form (CI half-widths are routinely quoted where the results record
    a full width), each rounded to 0-4 decimal places.
3.  Walk every `.md` file under `docs/` (plus `README.md`), strip the regions
    where numbers are not claims -- fenced code blocks, table alignment rows,
    heading and list ordinals, ADR filenames, identifier-embedded digits -- and
    extract what is left.
4.  Look each literal up in the value set at its own precision: a figure
    written to three decimals must equal some results value rounded to three
    decimals.
5.  Anything still unmatched is checked against ALLOWLIST. Anything that
    survives that is reported, with its line number and surrounding text.

Note the ordering in steps 4 and 5: the cheap structural exclusions (code
blocks, list markers) run before the lookup, but the *value-based* exclusions
(years, allowlist) run only against numbers that already failed to match. A
number that genuinely traces to the results is never quietly written off as a
year or an allowlist hit, so the allowlist cannot hide a live figure.

WHAT THIS CANNOT CATCH
----------------------
Stated plainly, because a check whose limits are not written down gets trusted
past them.

The audit is set membership, not provenance. It asks "does this number exist
somewhere in the results?", not "does this number mean what the sentence says
it means". `portfolio.json` currently holds about 1,500 distinct values; once
percentage and halved forms are included, roughly 80 percent of the three-
decimal grid on [0,1] is occupied. So a figure quoted to two or three decimals
can pass by coincidence -- matching a per-item mean from a different track
rather than the quantity the prose names. Precision is the defence: a
four-decimal figure has about a one-in-five chance of an accidental hit, and
counts and integers are usually unambiguous.

Two things follow. Quote figures at four decimals where the results record
them at four. And treat a clean run as the floor it is: it proves no figure in
the docs is *absent* from the current results, not that every figure is
attached to the right claim. Semantic checking needs the number and its
referent to be extracted together, which is a bigger project than this file.
"""


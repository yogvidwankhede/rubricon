# Decimal places at which a doc figure may be quoted. A figure written to more
# than four places is compared at four; nothing in this repository is reported
# more precisely than that.
MAX_DP = 4

# Slack allowed when comparing a doc literal against a rounded results value.
# Rounding already does the work; this only absorbs binary float representation
# error (0.1 + 0.2 arithmetic), so it is deliberately tiny.
TOLERANCE = 1e-9

# Years are excluded from the audit, but only after a number has already
# failed to match the results -- see the module docstring on ordering.
YEAR_MIN, YEAR_MAX = 1900, 2100


# --------------------------------------------------------------------------
# building the results value set
# --------------------------------------------------------------------------

# Numbers embedded in strings. The pipeline writes much of its evidence as
# prose ("alpha=0.5841 supports tentative conclusions", "range 0.100, p=0.9170")
# and a document quoting that prose is quoting the results, so those numbers
# have to count as sourced.
_NUM_IN_STRING = re.compile(r"[-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?")


def collect_results_values(obj: object, out: set[float]) -> None:
    """Recursively collect every number reachable in the results document."""
    if isinstance(obj, bool):
        return  # bools are ints in Python; they are not quantities
    if isinstance(obj, (int, float)):
        out.add(float(obj))
    elif isinstance(obj, str):
        for m in _NUM_IN_STRING.finditer(obj):
            try:
                out.add(float(m.group()))
            except ValueError:
                pass
    elif isinstance(obj, dict):
        for k, v in obj.items():
            # Keys carry numbers too ("0": 0.088 in a prevalence table).
            collect_results_values(k, out)
            collect_results_values(v, out)
    elif isinstance(obj, list):
        for v in obj:
            collect_results_values(v, out)


def derived_forms(values: set[float]) -> set[float]:
    """Forms a document would plausibly quote for a given results value.

    * the value itself;
    * the percentage form, because rates are recorded as fractions and quoted
      as percentages ("0.7611" -> "76.1 percent");
    * the halved form, because intervals are recorded as full widths and
      quoted as half-widths.
    """
    out: set[float] = set()
    for v in values:
        out.add(v)
        out.add(v * 100.0)
        out.add(v / 2.0)
    return out


def _round_half_up(value: float, dp: int) -> float:
    """Round away from zero at the midpoint, the way a person writing prose does.

    Python's ``round`` is banker's rounding applied to a binary float, so the
    results value 0.6365 becomes 0.636 at three places while an author quoting
    it writes 0.637. That is not a documentation error and it must not be
    reported as one, so both roundings are admitted. The two differ only on
    exact midpoints at the quoted precision, which is the narrowest possible
    widening: it cannot make a stale figure match anything it did not already
    round to.
    """
    q = Decimal(str(value)).quantize(Decimal(1).scaleb(-dp), rounding=ROUND_HALF_UP)
    return float(q)


def build_buckets(values: set[float]) -> dict[int, set[float]]:
    """Pre-round the value set to each precision a document might use."""
    buckets: dict[int, set[float]] = {}
    for dp in range(MAX_DP + 1):
        bucket = {round(v, dp) for v in values}
        bucket |= {_round_half_up(v, dp) for v in values}
        buckets[dp] = bucket
    return buckets


def is_sourced(literal: float, decimals: int, buckets: dict[int, set[float]]) -> bool:
    """Does this literal equal some results value at the literal's precision?"""
    dp = min(decimals, MAX_DP)
    target = round(literal, dp)
    bucket = buckets[dp]
    if target in bucket:
        return True
    # Fallback scan for float-representation edge cases. Cheap enough: this
    # only runs for the minority of literals that miss the exact lookup.
    return any(abs(target - v) <= TOLERANCE for v in bucket)


# --------------------------------------------------------------------------
# extracting numeric literals from prose
# --------------------------------------------------------------------------

_FENCE = re.compile(r"^\s*(```|~~~)")
# A markdown table alignment row: |---|:---:|---:|
_TABLE_RULE = re.compile(r"^\s*\|[\s:\-|]+\|\s*$")
# ISO dates, masked before extraction so 2026-05-02 does not yield 2026, 5, 2.
_ISO_DATE = re.compile(r"\b\d{4}-\d{2}-\d{2}\b")
# ADR filenames and cross-references: 0001-versioned-rubrics.md, "ADR 0003".
_ADR_REF = re.compile(r"\bADR[ -]?\d{4}\b|\b\d{4}-[a-z][a-z0-9-]*\.md\b")
# Leading ordinal of a heading ("## 3. Population") or a numbered list item.
_HEADING_ORDINAL = re.compile(r"^(#{1,6}\s+)\d+(?:\.\d+)*\.?\s")
_LIST_ORDINAL = re.compile(r"^(\s*)\d+[.)]\s")
# A bare number, possibly signed, possibly with thousands separators.
_LITERAL = re.compile(r"[-+]?\d[\d,]*(?:\.\d+)?")
# Characters that, immediately before or after a match, mean the digits are
# part of an identifier rather than a quantity: AF-01, sut-baseline-v1, r3,
# agentic-0042, 5xx, Sev-2, 0.15x.
_IDENT_CHARS = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_")


def strip_code_blocks(lines: list[str]) -> list[str]:
    """Blank out fenced code blocks, keeping line numbering intact."""
    out: list[str] = []
    in_fence = False
    for line in lines:
        if _FENCE.match(line):
            in_fence = not in_fence
            out.append("")
            continue
        out.append("" if in_fence else line)
    return out


def mask(text: str, pattern: re.Pattern[str]) -> str:
    """Replace every match with spaces, preserving column positions."""
    return pattern.sub(lambda m: " " * len(m.group()), text)


def literals_in_line(line: str) -> list[tuple[str, float, int]]:
    """Extract quantity-bearing literals from one line of prose.

    Returns (as-written, value, decimal places) triples.
    """
    if _TABLE_RULE.match(line):
        return []

    text = line
    text = mask(text, _ISO_DATE)
    text = mask(text, _ADR_REF)
    text = _HEADING_ORDINAL.sub(lambda m: m.group(1) + " " * (len(m.group()) - len(m.group(1))), text)
    text = _LIST_ORDINAL.sub(lambda m: m.group(1) + " " * (len(m.group()) - len(m.group(1))), text)

    found: list[tuple[str, float, int]] = []
    for m in _LITERAL.finditer(text):
        raw = m.group()
        start, end = m.span()

        # Digits welded to letters or to a hyphenated identifier are not
        # quantities. "AF-01", "sut-candidate-v3", "r3", "5xx", "n=48" is fine
        # because '=' is not an identifier character.
        before = text[start - 1] if start > 0 else ""
        after = text[end] if end < len(text) else ""
        if before in _IDENT_CHARS or after in _IDENT_CHARS:
            continue
        # A sign glued to a preceding digit is a range ("2-3 instances"), not a
        # negative number; the leading operand was already captured separately.
        if raw[0] in "+-" and before.isdigit():
            continue
        # Leading-zero integers are identifiers or ordinals (0001, AF-04's 04).
        body = raw.lstrip("+-")
        if len(body) > 1 and body[0] == "0" and "." not in body:
            continue
        # A digit followed by '.' and then a non-digit is a sentence ordinal.
        if after == "." and "." not in raw:
            nxt = text[end + 1] if end + 1 < len(text) else " "
            if not nxt.isdigit():
                pass  # keep it: "48." at end of a sentence is still a quantity

        try:
            value = float(body.replace(",", "")) * (-1.0 if raw[0] == "-" else 1.0)
        except ValueError:
            continue
        decimals = len(body.split(".")[1]) if "." in body else 0
        found.append((raw, value, decimals))
    return found


# --------------------------------------------------------------------------
# allowlist handling
# --------------------------------------------------------------------------

def split_allowlist() -> tuple[dict[float, str], list[tuple[re.Pattern[str], str]]]:
    """Split ALLOWLIST into exact values and line patterns, validating it."""
    values: dict[float, str] = {}
    patterns: list[tuple[re.Pattern[str], str]] = []
    for key, justification in ALLOWLIST.items():
        if not isinstance(justification, str) or not justification.strip():
            raise SystemExit(
                f"ALLOWLIST entry {key!r} has no justification. Every entry must "
                "say why the number does not come from results; an unjustified "
                "entry defeats the purpose of the audit."
            )
        if key.startswith("re:"):
            patterns.append((re.compile(key[3:]), justification))
        else:
            values[float(key)] = justification
    return values, patterns


def allowlist_hit(
    value: float,
    line: str,
    values: dict[float, str],
    patterns: list[tuple[re.Pattern[str], str]],
) -> str | None:
    """Return the justification if this number is allowlisted, else None."""
    stripped = line.strip()
    for pattern, justification in patterns:
        if pattern.search(stripped):
            return justification
    for allowed, justification in values.items():
        if abs(value - allowed) <= TOLERANCE:
            return justification
    return None


